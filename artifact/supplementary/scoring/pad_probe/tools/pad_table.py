"""pad_table.py -- the Appendix D.2 table of the padding probe (ADDENDUM_PAD section 7: whole-set AUROC by length for the
three readers with the paired intervals) and its Amendment 1 block (the contaminated lists on the 444), written from
results/pad_scores.json and results/contam_scores.json to pad_probe/paper_table.tex; and the AUX-PAD-PRINTED section
(the two-decimal forms Section 5 prints, beside their four-decimal sources) appended to NUMBERS_PAD.md between markers,
so that ledger_pad.py's regeneration is not disturbed. NO MODEL CALL, NO RECOMPUTATION: every value is read from the
score artifacts the ledger already prints. Usage: python pad_probe/tools/pad_table.py
"""
from __future__ import annotations

import io
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
PAD = ROOT / "pad_probe"
RES = PAD / "results"
LEDGER = PAD / "NUMBERS_PAD.md"
BEGIN, END = "<!-- AUX-PAD-PRINTED BEGIN (pad_table.py) -->", "<!-- AUX-PAD-PRINTED END -->"
BS = "\\"


def J(p):
    return json.load(io.open(p, encoding="utf-8"))


def ci(c):
    return f"$[{c['ci_lo']:+.4f},{c['ci_hi']:+.4f}]$"


def main():
    S = J(RES / "pad_scores.json")["readers"]; C = J(RES / "contam_scores.json")["readers"]
    L = [BS + "begin{table}[H]",
         "% R107 (2026-09-14): the padding probe (registrations/ADDENDUM_PAD.md, sha256 93e33022...; pad_probe/NUMBERS_PAD.md AUX-PAD-LOOKUP-EMB, -LOOKUP-LEX, -MINI) and its",
         "% Amendment 1 (AUX-PAD-C-LOOKUP-EMB, -C-LOOKUP-LEX, -C-MINI, -C-H45); regenerated by pad_probe/tools/pad_table.py; do not edit by hand.",
         BS + "caption{The list-length check and its amendment. Upper block: the superseded-names list of each of the $661$ main-study summaries padded with correct attribute names that no scored question of the persona targets, "
         "to $15$, $30$ and $60$ names; obligation AUROC of each reader against its recorded $1.75$-name row, with the paired difference and both intervals. "
         "Lower block: the counterfactual set's $444$ superseded-only summaries with wrong names injected into the negatives' lists at the lifecycle store's measured rate ($0.232$) and at $0.40$; "
         "AUROC against the recorded list, the paired difference and both intervals, and for the models the difference from the embedding lookup on the same lists (the weaker of the two intervals). "
         "Descriptive; no prediction was registered, and every branch prints as it came out.}",
         BS + "label{tab:pad}", BS + "centering", BS + "scriptsize", BS + "setlength{" + BS + "tabcolsep}{3pt}",
         BS + "begin{tabular}{@{}llrrll@{}}", BS + "toprule",
         "Reader & list & AUROC & $" + BS + "Delta$ vs recorded & item interval & profile interval " + BS + BS, BS + "midrule",
         BS + "multicolumn{6}{@{}l}{" + BS + "textit{Padding with correct names, the $661$ questions, truthful summary}}" + BS + BS]
    names = {"emb": "Superseded-names lookup", "lex": "Lexical lookup", "mini": "GPT-4.1 mini"}
    for k in ("emb", "lex", "mini"):
        r = S[k]; b = r["base"]
        L.append(f"{names[k]} & $1.75$ names & ${b['auroc']:.4f}$ & -- & -- & -- " + BS + BS)
        for Lx in ("15", "30", "60"):
            x = r[Lx]; p = x["paired_vs_base"]
            L.append(f"{names[k]} & ${Lx}$ names & ${x['auroc']:.4f}$ & ${p['delta']:+.4f}$ & {ci(p['ci_item'])} & {ci(p['ci_persona'])} " + BS + BS)
    L += [BS + "bottomrule", BS + "end{tabular}" + BS + BS + "[6pt]",
         BS + "setlength{" + BS + "tabcolsep}{2pt}", BS + "begin{tabular}{@{}llrrll@{}}", BS + "toprule",
         "Reader & list & AUROC & $" + BS + "Delta$ & intervals (item; profile) & minus lookup (weaker) " + BS + BS, BS + "midrule",
         BS + "multicolumn{6}{@{}l}{" + BS + "textit{Wrong names injected, the counterfactual set ($444$), superseded-only summary}}" + BS + BS]
    cnames = {"emb": "Emb.\\ lookup", "lex": "Lex.\\ lookup", "MINI": "GPT-4.1 mini", "H45": "Haiku 4.5"}
    for k in ("emb", "lex", "MINI", "H45"):
        r = C[k]; b = r["base"]
        L.append(f"{cnames[k]} & recorded & ${b['auroc']:.4f}$ & -- & -- & -- " + BS + BS)
        for arm, lab in (("INDEXED-V2-C0.232", "$c=0.232$"), ("INDEXED-V2-C0.40", "$c=0.40$")):
            x = r[arm]; p = x["paired_vs_recorded"]
            extra = "--"
            if "model_minus_emb" in x:
                m = x["model_minus_emb"]; w = m["weaker"]
                extra = f"${m['delta']:+.4f}$ $[{w['ci_lo']:+.4f},{w['ci_hi']:+.4f}]$"
            L.append(f"{cnames[k]} & {lab} & ${x['auroc']:.4f}$ & ${p['delta']:+.4f}$ & {ci(p['ci_item'])}; {ci(p['ci_persona'])} & {extra} " + BS + BS)
    L += [BS + "bottomrule", BS + "end{tabular}", BS + "end{table}"]
    (PAD / "paper_table.tex").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("wrote", PAD / "paper_table.tex")

    # the printed forms
    e, lx, mi = S["emb"], S["lex"], S["mini"]
    ce, cm, ch = C["emb"], C["MINI"], C["H45"]
    P = ["", BEGIN, "", "## 6. AUX-PAD-PRINTED — the two-decimal forms Section 5 prints, against their four-decimal sources (the R97/R102 printed-forms convention; written by `tools/pad_table.py`, R107)", "",
         "| printed | source |", "|---|---|",
         f"| $0.75$ to $0.73$, $0.72$ and $0.67$ at $15$, $30$ and $60$ names | AUX-PAD-LOOKUP-EMB whole: {e['base']['auroc']:.4f} → {e['15']['auroc']:.4f} / {e['30']['auroc']:.4f} / {e['60']['auroc']:.4f} |",
         f"| the lexical lookup flat ($0.57$ to $0.58$) | AUX-PAD-LOOKUP-LEX whole: {lx['base']['auroc']:.4f} → {lx['15']['auroc']:.4f} / {lx['30']['auroc']:.4f} / {lx['60']['auroc']:.4f}; AUX-PAD-BRANCH flat |",
         f"| $0.73$ to $0.67$, $0.66$ and $0.69$ | AUX-PAD-MINI whole: {mi['base']['auroc']:.4f} → {mi['15']['auroc']:.4f} / {mi['30']['auroc']:.4f} / {mi['60']['auroc']:.4f}; AUX-PAD-BRANCH degrades, first at 15 |",
         f"| $-0.08$ at $60$ names, item interval excluding zero and profile interval including it | AUX-PAD-LOOKUP-EMB 60: {e['60']['paired_vs_base']['delta']:+.4f}, item {ci(e['60']['paired_vs_base']['ci_item'])}, persona {ci(e['60']['paired_vs_base']['ci_persona'])} |",
         f"| $0.77$ to $0.67$ and $0.60$ | AUX-PAD-C-LOOKUP-EMB whole: {ce['base']['auroc']:.4f} → {ce['INDEXED-V2-C0.232']['auroc']:.4f} / {ce['INDEXED-V2-C0.40']['auroc']:.4f} |",
         f"| $0.72$ to $0.68$ and $0.61$ | AUX-PAD-C-MINI whole: {cm['base']['auroc']:.4f} → {cm['INDEXED-V2-C0.232']['auroc']:.4f} / {cm['INDEXED-V2-C0.40']['auroc']:.4f} |",
         f"| $0.76$ to $0.68$ and $0.62$ | AUX-PAD-C-H45 whole: {ch['base']['auroc']:.4f} → {ch['INDEXED-V2-C0.232']['auroc']:.4f} / {ch['INDEXED-V2-C0.40']['auroc']:.4f} |",
         f"| each model within $0.02$ of the lookup on the same lists, intervals including zero | AUX-PAD-C-MINI minus emb {cm['INDEXED-V2-C0.232']['model_minus_emb']['delta']:+.4f} / {cm['INDEXED-V2-C0.40']['model_minus_emb']['delta']:+.4f}; AUX-PAD-C-H45 {ch['INDEXED-V2-C0.232']['model_minus_emb']['delta']:+.4f} / {ch['INDEXED-V2-C0.40']['model_minus_emb']['delta']:+.4f}; every weaker interval includes zero |",
         "", END, ""]
    t = LEDGER.read_text(encoding="utf-8")
    if BEGIN in t:
        t = t[:t.index(BEGIN)].rstrip("\n") + "\n" + "\n".join(P[1:]) + t[t.index(END) + len(END):].lstrip("\n")
    else:
        t = t.rstrip("\n") + "\n" + "\n".join(P)
    LEDGER.write_text(t, encoding="utf-8", newline="\n")
    print("AUX-PAD-PRINTED written into", LEDGER)
    for k in ("emb", "lex", "mini"):
        print(k, [round(S[k][x]["auroc"], 4) for x in ("base", "15", "30", "60")] if "auroc" in S[k]["base"] else "")
    for k in ("emb", "MINI", "H45"):
        print(k, [round(C[k][x]["auroc"], 4) for x in ("base", "INDEXED-V2-C0.232", "INDEXED-V2-C0.40")], [round(C[k][x]["model_minus_emb"]["delta"], 4) for x in ("INDEXED-V2-C0.232", "INDEXED-V2-C0.40") if "model_minus_emb" in C[k][x]])


if __name__ == "__main__":
    main()
