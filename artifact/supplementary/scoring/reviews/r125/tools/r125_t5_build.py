# -*- coding: utf-8 -*-
"""r125_t5_build.py -- Task 5 (E2 Amendment 1): the names-only and counts-only renderings of the 444, E2's own renderer, byte-checked. $0.

The two renderings are cf2_names_counts.names_only and counts_only applied to the recorded v2 text of every item (the primary line-removal
forms of E2; the dash rule is not run), with E2's locks asserted on every version (cf2_names_counts.locks) and the per-arm texts sha256
asserted equal to the recorded build (cf2/build_nc.json, AUX-CF2-NC-LOCK): the texts the three strong models will read are the very texts
GPT-4.1 mini and Haiku 4.5 read in E2. Writes reviews/r125/build/build_t5_nc.json (the arms' sha256 and token census; the texts themselves are
regenerated by the runner from the same function and asserted against the sha256 at every start).
"""
from __future__ import annotations

import hashlib
import sys

sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parent))
import r125_common as C  # noqa: E402
import cf2_names_counts as NC  # noqa: E402

OUT = C.BUILD / "build_t5_nc.json"
ARMS = ("INDEXED-NAMES", "INDEXED-COUNTS")


def texts_for(arm):
    """item_id -> rendered text, E2's function on the recorded v2 texts."""
    return {it["item_id"]: NC.RENDER[arm](NC.RC.IDX[it["item_id"]]["v2"]) for it in NC.RC.CELL}


def arm_sha(texts, cell_ids):
    shas = [hashlib.sha256(texts[i].encode("utf-8")).hexdigest() for i in cell_ids]
    return hashlib.sha256("".join(shas).encode()).hexdigest()


def main():
    rec_nc = C.jload(C.CF2 / "build_nc.json")["arms"]
    cell_ids = [it["item_id"] for it in NC.RC.CELL]
    out = {"meta": {"script": "reviews/r125/tools/r125_t5_build.py", "renderer": "r82_counterfactual/tools/cf2_names_counts.py names_only / counts_only (E2's primary forms)", "model_calls": 0,
                    "renderer_sha256": C.sha_file(C.ROOT / "r82_counterfactual" / "tools" / "cf2_names_counts.py")}, "arms": {}}
    for arm in ARMS:
        T = texts_for(arm)
        for it in NC.RC.CELL:
            NC.locks(NC.RC.IDX[it["item_id"]]["v2"], arm, T[it["item_id"]])
        sha = arm_sha(T, cell_ids)
        assert sha == rec_nc[arm]["texts_sha256"], (arm, sha, rec_nc[arm]["texts_sha256"])
        chars = [len(T[i]) for i in cell_ids]
        out["arms"][arm] = {"n": len(T), "texts_sha256": sha, "recorded_texts_sha256": rec_nc[arm]["texts_sha256"], "byte_check": "PASS", "lock": "cf2_names_counts.locks asserted on every version",
                            "chars_mean": round(sum(chars) / len(chars), 1), "recorded_prompt_tokens_mean": rec_nc[arm]["prompt_tokens_mean"]}
        print(f"{arm}: {len(T)} texts, sha256 {sha[:16]} == recorded (E2's build), locks asserted on every version; chars mean {out['arms'][arm]['chars_mean']}, E2's token mean {rec_nc[arm]['prompt_tokens_mean']}")
    C.jdump(out, OUT)
    print(f"-> {OUT.relative_to(C.ROOT)}")


if __name__ == "__main__":
    main()
