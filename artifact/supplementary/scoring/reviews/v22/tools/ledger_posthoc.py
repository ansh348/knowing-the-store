# -*- coding: utf-8 -*-
"""ledger_posthoc.py -- writes the ledger sections 8 to 10 of reviews/NUMBERS_WP.md (AUX-WP-B-*, AUX-WP-B4-*, AUX-WP-F1-*) and the
LaTeX table bodies reviews/v19/src/posthoc_tables_v19.tex from the three post-hoc result files, so no printed number is transcribed
by hand (program R112, 2026-09-16). NO MODEL CALL. Idempotent: replaces the generated block between its markers.
Usage: python reviews/v19/tools/ledger_posthoc.py
"""
from __future__ import annotations

import io
import json
import pathlib
from decimal import Decimal, ROUND_HALF_UP

ROOT = pathlib.Path(__file__).resolve().parents[3]
RES = ROOT / "reviews" / "v19" / "results"
LEDGER = ROOT / "reviews" / "NUMBERS_WP.md"
TEX = ROOT / "reviews" / "v19" / "src" / "posthoc_tables_v19.tex"
BEGIN, END = "<!-- POSTHOC-LEDGER-BEGIN (generated by reviews/v19/tools/ledger_posthoc.py; do not edit by hand) -->", "<!-- POSTHOC-LEDGER-END -->"
STATES = ("SUPERSESSION", "RETRACTION", "EXPIRY")
READERS = [("gpt-4.1-mini | v2", "GPT-4.1 mini, sup.\\ only"), ("gpt-4.1-mini | v3", "GPT-4.1 mini, all three"),
           ("claude-haiku-4-5-20251001 | v2", "Haiku 4.5, sup.\\ only"), ("claude-haiku-4-5-20251001 | v3", "Haiku 4.5, all three"),
           ("claude-opus-5 | v2", "Opus 5, sup.\\ only"), ("claude-opus-5 | v3", "Opus 5, all three"),
           ("name lookup | v2", "Name lookup, sup.\\ only"), ("all-states lookup | v3", "All-states lookup, all three"),
           ("category-guessing count reader | v2", "Category-guessing count reader, sup.\\ only"),
           ("category-aware count reader | v2", "Category-aware count reader, sup.\\ only")]


def two(x):
    return str(Decimal(str(x)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP))


def f4(x):
    return f"{x:.4f}"


def ci(d, signed=False):
    fmt = "{:+.4f}" if signed else "{:.4f}"
    return "[" + fmt.format(d["ci_lo"]) + ", " + fmt.format(d["ci_hi"]) + "]"


def main():
    B = json.load(io.open(RES / "posthoc_b.json", encoding="utf-8"))
    B4 = json.load(io.open(RES / "posthoc_b4.json", encoding="utf-8"))
    F1 = json.load(io.open(RES / "posthoc_f1.json", encoding="utf-8"))
    md, tex = [], []
    md.append(BEGIN)
    md.append("\n## 8. AUX-WP-B-PNPRESENT, AUX-WP-B-ORDERING, AUX-WP-B-COVONLY: PN-versus-PRESENT discrimination, within-triple ordering and the coverage-only reference on the counterfactual set (post hoc, specified before recomputation; `reviews/v19/tools/posthoc_b_pnpresent.py`, `reviews/v19/results/posthoc_b.json`)\n")
    md.append(f"Gates reproduced: {B['gates']}. Coverage-only reference (s = 1 on PN and PRESENT, 0 on ABSENT): whole {B['coverage_only']['whole']}, per state {B['coverage_only']['per_state']}; its PN-vs-PRESENT AUROC is 0.5000 by construction (every triple a tie). The pooled AUROC equals the mean of PN-vs-PRESENT and PN-vs-ABSENT on every row (asserted to four decimals).\n")
    md.append("| reader | summary | scope | n pairs | PN vs PRESENT | persona interval | PN vs ABSENT | pooled | wins / ties / losses | strict-win fraction | persona interval | Wilson |")
    md.append("|---|---|---|---:|---:|---|---:|---:|---|---:|---|---|")
    for key, label in READERS:
        row = B["readers"][key]
        reader, tag = key.split(" | ")
        for scope, b in (("whole", row["whole"]),) + tuple((s_.lower(), row["per_state"][s_]) for s_ in STATES):
            o = b["ordering"]
            md.append(f"| {reader} | {tag} | {scope} | {b['n_pairs']} | {f4(b['pn_vs_present'])} | {ci(b['pn_vs_present_ci_persona'])} | {f4(b['pn_vs_absent'])} | {f4(b['pooled'])} | "
                      f"{o['wins']} / {o['ties']} / {o['losses']} | {f4(o['strict_win_fraction'])} | {ci(o['ci_persona'])} | [{f4(o['wilson'][0])}, {f4(o['wilson'][1])}] |")
    md.append("\nPrinted forms (Table 2's two new columns, whole set; ROUND_HALF_UP):\n")
    md.append("| reader, summary | PN vs PRESENT printed | four-decimal | wins / ties / losses |")
    md.append("|---|---:|---:|---|")
    for key, label in READERS:
        b = B["readers"][key]["whole"]; o = b["ordering"]
        md.append(f"| {label.replace(chr(92), '')} | {two(b['pn_vs_present'])} | {f4(b['pn_vs_present'])} | {o['wins']} / {o['ties']} / {o['losses']} |")
    md.append("| the largest move from the pooled value, any reader, whole set | 0.03 | max |pooled - PN vs PRESENT| = " +
              f4(max(abs(B['readers'][k]['whole']['pooled'] - B['readers'][k]['whole']['pn_vs_present']) for k, _ in READERS)) + " | |")
    # B4
    md.append("\n## 9. AUX-WP-B4-INTENT: the intent-aware lookup on the 661, and the items where intent alone decides the label (post hoc, specified before recomputation; `reviews/v19/tools/posthoc_b4_intent.py`, `reviews/v19/results/posthoc_b4.json`)\n")
    md.append(f"Not definable: {B4['meta']['not_definable']}. Gates reproduced: {B4['gates']}.\n")
    md.append("| lookup on the 661 (104 positives) | plain | intent-aware | items zeroed | aware minus plain | item interval | persona interval |")
    md.append("|---|---:|---:|---|---:|---|---|")
    for k, v in B4["B4a"].items():
        z = v.get("items_zeroed", None)
        zz = f"{z} CHANGE-AWARE" if z is not None else f"{v['items_zeroed_change']} CHANGE-AWARE, {v['items_zeroed_past']} PAST-EVENT with an expired best match"
        a = v["aware_minus_plain"]
        md.append(f"| {k.replace('_', ' ')} | {f4(v['plain'])} | {f4(v['intent_aware'])} | {zz} | {a['delta']:+.4f} | {ci(a['item_ci'], True)} | {ci(a['persona_ci'], True)} |")
    bb = B4["B4b"]
    md.append(f"\nB4b: CHANGE-AWARE licensed items {bb['change_aware_licensed']}; own gold slot holds a join-superseded record: {bb['own_slot_holds_superseded']} "
              f"(status: {bb.get('status', 'defined')}); of them the plain lookup flags {bb['flagged_at_base_rate_threshold']['own_slot_items']} at the base-rate threshold "
              f"{f4(bb['base_rate_threshold'])} (the 104th-highest lookup score); over all {bb['change_aware_licensed']} CHANGE-AWARE licensed items it flags {bb['flagged_at_base_rate_threshold']['all_change_aware_licensed']}. "
              f"B4c (descriptive, {bb['own_slot_holds_superseded']} items, below the spec's floor of 5, not printed in the paper): " +
              "; ".join(f"{m}: median NOK {q['own_slot_change_items'].get('median')} on the {q['own_slot_change_items'].get('n')} items against {q['supersession_obligations']['median']} on the 63 supersession obligations" for m, q in B4["B4c"]["monitors"].items()) + ".\n")
    # F1
    md.append("\n## 10. AUX-WP-F1-WHOLEMAP: the whole-map embedding lookup on the FR-Bank easy tier (post hoc, specified before recomputation; `reviews/v19/tools/posthoc_f1_wholemap.py`, `reviews/v19/results/posthoc_f1.json`)\n")
    md.append(f"Gates reproduced: {F1['gates']}. Reader: {F1['meta']['reader']}.\n")
    md.append("| population | n / pos | monitor indexed | superseded-section lookup | whole-map lookup | persona interval | whole-map lexical | model minus whole-map | item interval | persona interval | reading | map names / item |")
    md.append("|---|---|---:|---:|---:|---|---:|---:|---|---|---|---:|")
    for rid, d in F1["populations"].items():
        m = d["model_minus_whole_embedding"]
        md.append(f"| {d['label']} | {d['n']} / {d['pos']} | {f4(d['monitor_indexed'])} | {f4(d['lookup_sup_embedding'])} | {f4(d['lookup_whole_embedding'])} | {ci(d['lookup_whole_embedding_ci_persona'])} | "
                  f"{f4(d['lookup_whole_lexical'])} | {m['delta']:+.4f} | {ci(m['item_ci'], True)} | {ci(m['persona_ci'], True)} | {d['reading']} | {d['mean_map_names_per_item']} |")
    e = F1["populations"]["R-FOK-EASY-FRB"]; m = e["model_minus_whole_embedding"]
    md.append(f"\nPrinted forms: whole-map lookup {two(e['lookup_whole_embedding'])} ({f4(e['lookup_whole_embedding'])}); model minus whole-map {m['delta']:+.2f} ({m['delta']:+.4f}), "
              f"item [{m['item_ci']['ci_lo']:+.2f},{m['item_ci']['ci_hi']:+.2f}], persona [{m['persona_ci']['ci_lo']:+.2f},{m['persona_ci']['ci_hi']:+.2f}]; the superseded-section margin +0.18 (+0.1752) stands in AUX-R104-COV-LOOKUP.\n")
    md.append(END)

    text = LEDGER.read_text(encoding="utf-8")
    if BEGIN in text:
        text = text[:text.index(BEGIN)] + "\n".join(md) + text[text.index(END) + len(END):]
    else:
        text = text.rstrip("\n") + "\n\n" + "\n".join(md) + "\n"
    LEDGER.write_text(text, encoding="utf-8", newline="\n")

    # ---- LaTeX: the C.2 per-state table
    tex.append("% posthoc_tables_v19.tex -- generated by reviews/v19/tools/ledger_posthoc.py from reviews/v19/results/posthoc_b.json (AUX-WP-B-*); do not edit by hand.")
    tex.append("\\begin{table}[H]")
    tex.append("\\caption{PN-versus-PRESENT discrimination and within-triple ordering on the counterfactual set, per reader, summary and state (post hoc, specified before recomputation). PN vs PRESENT is the AUROC of the PN versions against the PRESENT versions alone (the ABSENT versions excluded), with the persona-grouped interval; the pooled AUROC of Table~\\ref{tab:cf-main} is the mean of this column and the PN-vs-ABSENT AUROC, which the artifact's ledger carries beside the Wilson intervals. W/T/L counts the triples in which the reader scores the PN version above, equal to, or below the PRESENT version; the strict-win fraction counts ties as failures, is not a tie-adjusted ranking accuracy, and its chance reference is not $0.50$ when ties occur. A reader that only knows whether the store covers the question scores $0.75$ pooled and $0.50$ PN vs PRESENT (every triple a tie).}")
    tex.append("\\label{tab:pnpresent}")
    tex.append("\\centering\\scriptsize\\setlength{\\tabcolsep}{1.5pt}")
    tex.append("\\begin{tabular}{@{}llrlr@{\\hspace{3pt}}rrl@{}}")
    tex.append("\\toprule")
    tex.append("Reader, summary & scope & PN vs PRESENT & persona interval & pooled & W/T/L & strict-win & persona interval \\\\")
    tex.append("\\midrule")
    for key, label in READERS:
        row = B["readers"][key]
        for j, (scope, b) in enumerate((("whole", row["whole"]),) + tuple((s_.lower()[:3] + ".", row["per_state"][s_]) for s_ in STATES)):
            o = b["ordering"]; c = b["pn_vs_present_ci_persona"]; oc = o["ci_persona"]
            lab = label if j == 0 else ""
            tex.append(f"{lab} & {scope} & ${f4(b['pn_vs_present'])}$ & $[{f4(c['ci_lo'])},{f4(c['ci_hi'])}]$ & ${f4(b['pooled'])}$ & "
                       f"${o['wins']}/{o['ties']}/{o['losses']}$ & ${f4(o['strict_win_fraction'])}$ & $[{f4(oc['ci_lo'])},{f4(oc['ci_hi'])}]$ \\\\")
        tex.append("\\addlinespace[1pt]")
    tex.append("\\bottomrule")
    tex.append("\\end{tabular}")
    tex.append("\\end{table}")
    TEX.write_text("\n".join(tex) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {LEDGER.relative_to(ROOT)} sections 8-10 and {TEX.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
