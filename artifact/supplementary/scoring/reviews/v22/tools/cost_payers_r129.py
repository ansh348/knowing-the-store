"""cost_payers_r129.py -- the costed table of R129's body landings (2026-09-20): for each of the seven body changes (A1 the MemoryAgentBench sentence,
A2 the Section 7 parenthetical, S4 the count sentence, B1 the moved-count paragraph, B2 the hybrid paragraph, C1 and C2 the two payers), the body with
that one change reverted is built in place and the fine number read (reviews/v22/tools/fine.py), so each change's cost or gain in lines stands beside
the aggregate; then the body with every R129 change reverted (the R128 close) as the check. Each reversal is an asserted replacement of the new text by
the text it replaced. The body is regenerated by port_v22.py at the end, so nothing this script writes survives it.
Usage: python reviews/v22/tools/cost_payers_r129.py
"""
from __future__ import annotations

import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
TOOLS = ROOT / "reviews" / "v22" / "tools"
BODY = ROOT / "reviews" / "v22" / "src" / "body_v22.tex"
OUT = ROOT / "reviews" / "v22" / "results" / "cost_payers_r129.md"


def fine():
    out = subprocess.run([sys.executable, str(TOOLS / "fine.py")], capture_output=True, text=True).stdout
    m = re.search(r"main-text-end page (\d+); fine number (\d+)", out)
    return int(m.group(1)), int(m.group(2))


