def main():
    subprocess.run([sys.executable, str(TOOLS / "port_v22.py")], check=True, capture_output=True)
    base = BODY.read_text(encoding="utf-8")
    page0, fine0 = fine()
    rows = [f"| as landed (every R129 change) | {page0} | {fine0} | {485 - fine0:+d} |"]
    try:
        for name, new, old in VARIANTS:
            assert base.count(new) == 1, (name, base.count(new))
            BODY.write_text(base.replace(new, old), encoding="utf-8", newline="\n")
            p, f = fine()
            rows.append(f"| {name} reverted alone | {p} | {f} | {485 - f:+d} | {f - fine0:+d} lines |")
            print(rows[-1], flush=True)
        t = base
        for name, new, old in VARIANTS:
            t = t.replace(new, old)
        BODY.write_text(t, encoding="utf-8", newline="\n")
        p, f = fine()
        rows.append(f"| every R129 change reverted (the R128 close) | {p} | {f} | {485 - f:+d} | {f - fine0:+d} lines |")
        print(rows[-1], flush=True)
        t = base
        for name, new, old in VARIANTS:
            if name.startswith("C"):
                t = t.replace(new, old)
        BODY.write_text(t, encoding="utf-8", newline="\n")
        p, f = fine()
        rows.append(f"| the two payers reverted (A, S4 and B without C) | {p} | {f} | {485 - f:+d} | {f - fine0:+d} lines |")
        print(rows[-1], flush=True)
    finally:
        subprocess.run([sys.executable, str(TOOLS / "port_v22.py")], check=True, capture_output=True)
        subprocess.run([sys.executable, str(TOOLS / "build_v22.py")], check=True, capture_output=True)
    md = ["# The costed table of R129's body landings (reviews/v22/tools/cost_payers_r129.py, 2026-09-20)", "",
          "Each row: the body with that one change reverted, built in place, the fine number read by fine.py (the gate is 485 or lower). A negative line count is what the change costs; a positive one is what the payer pays.", "",
          "| variant | page | fine number | against 485 | difference from the landing |", "|---|---:|---:|---:|---:|"] + rows
    OUT.write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")
    print("->", OUT)


if __name__ == "__main__":
    main()
